import fs from "fs";
import path from "path";
import yaml from "js-yaml";

/**
 * Non-secret configuration, shared with the Python service via config.yaml.
 * Only the fields the HomeKit app cares about are typed here.
 */
export interface AppConfig {
  cameraName: string;
  rtspUrl: string;
  motionPort: number;
  motionTimeout: number;
  width: number;
  height: number;
  fps: number;
  qrWebPort: number;
  snapshotPath: string;
  bitrateKbps: number;
  cameraControlUrl: string;
  ffmpegPath: string;
}

/** The lean static build (scripts/build-static-ffmpeg.sh) installs here. */
const STATIC_FFMPEG = "/opt/pi4cam/bin/ffmpeg-static";

/**
 * Which ffmpeg to spawn for live sessions and the HKSV prebuffer.
 * Debian's ffmpeg links ~150 shared libraries and costs 5-8 s just to start
 * on a memory-pressured 512 MB Pi (#43); the optional lean static build
 * starts in ~0.2 s. Explicit config wins, then the static build if present,
 * then the system ffmpeg.
 */
function resolveFfmpeg(configured: unknown): string {
  if (configured) {
    return String(configured);
  }
  if (fs.existsSync(STATIC_FFMPEG)) {
    return STATIC_FFMPEG;
  }
  return "ffmpeg";
}

/**
 * Pairing secrets generated by install.sh into pairing.json. Never committed.
 *   username : accessory MAC (XX:XX:XX:XX:XX:XX, locally administered)
 *   pincode  : HomeKit setup code (XXX-XX-XXX)
 *   setupID  : 4-char setup ID used in the QR code
 */
export interface Pairing {
  username: string;
  pincode: string;
  setupID: string;
}

function candidatePaths(filename: string): string[] {
  return [
    path.resolve(__dirname, "..", "..", filename), // repo root (dev)
    path.join("/opt/pi4cam", filename), // installed location
  ];
}

function firstExisting(filename: string): string {
  for (const p of candidatePaths(filename)) {
    if (fs.existsSync(p)) {
      return p;
    }
  }
  throw new Error(
    `${filename} not found (looked in: ${candidatePaths(filename).join(", ")})`,
  );
}

/**
 * The homekit/ working directory (holds pairing.json + the persist/ store).
 * Installed at /opt/pi4cam/homekit; falls back to the repo's homekit/ in dev.
 */
export function homekitDir(): string {
  const installed = "/opt/pi4cam/homekit";
  if (fs.existsSync(installed)) {
    return installed;
  }
  return path.resolve(__dirname, "..");
}

export function loadConfig(): AppConfig {
  const raw = yaml.load(fs.readFileSync(firstExisting("config.yaml"), "utf8")) as
    | Record<string, any>
    | undefined;
  const cfg = raw ?? {};
  const camera = cfg.camera ?? {};
  const rtsp = cfg.rtsp ?? {};
  const homekit = cfg.homekit ?? {};

  const rtspPort = Number(rtsp.port ?? 8554);

  return {
    cameraName: String(homekit.camera_name ?? "Pi Camera"),
    rtspUrl: `rtsp://127.0.0.1:${rtspPort}/camera`,
    motionPort: Number(homekit.motion_port ?? 8989),
    motionTimeout: Number(homekit.motion_timeout ?? 10),
    width: Number(camera.width ?? 1920),
    height: Number(camera.height ?? 1080),
    fps: Number(camera.fps ?? 30),
    qrWebPort: Number(homekit.qr_web_port ?? 8080),
    snapshotPath: String(camera.snapshot_path ?? "/dev/shm/pi4cam-snapshot.jpg"),
    // config.yaml stores bitrate in bit/s; the bitrate governor thinks in kbps.
    bitrateKbps: Math.round(Number(camera.bitrate ?? 4_000_000) / 1000),
    cameraControlUrl: `http://127.0.0.1:${Number(camera.control_port ?? 8990)}`,
    ffmpegPath: resolveFfmpeg(homekit.ffmpeg_path),
  };
}

export function loadPairing(): Pairing {
  const p = path.join(homekitDir(), "pairing.json");
  if (!fs.existsSync(p)) {
    throw new Error(
      `${p} not found — run install.sh to generate the pairing secrets`,
    );
  }
  const data = JSON.parse(fs.readFileSync(p, "utf8")) as Partial<Pairing>;
  if (!data.username || !data.pincode || !data.setupID) {
    throw new Error(`${p} is missing username/pincode/setupID`);
  }
  return data as Pairing;
}
